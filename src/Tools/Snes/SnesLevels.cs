    /// <summary>
    /// Converts data/levels (through the C# LevelLoader, so the grids are exactly what the Windows game sees) and the
    /// level tiles of data/art into SNES data for the engine (snes/src/game.s + eng_*.s):
    ///  * gen/levels.inc  constants (LEVEL_COUNT, T_* tile types, CT_* contents, engine tileset ids)
    ///  * gen/eng_levels.s  level directory, level/area headers, LZ-compressed tile + metatile grids, sparse lists
    ///  * gen/eng_tiles.s  per-theme BG1 tilesets: 4bpp CHR, metatile table (4 tilemap words each), 4 palettes of 15
    ///    colors (BG palettes 2-5), animated CHR frames, runtime metatile table for tiles that change
    ///  * gen/eng_font.s  2bpp HUD/menu font for BG3
    /// Data goes only into BANK40-BANK55 (see DESIGN.md "API requests").
    /// </summary>
    public static class SnesLevels
    {
        public const int FirstBank = 40, LastBank = 51;
        public static readonly string[] Themes = { "plains", "underground", "desert", "sea", "jungle", "sky", "ice", "machine", "volcano", "fortress", "castle", "airship", "bonus" };
        public static readonly string[] Scrolls = { "normal", "free", "lock", "vertical", "auto" };

        /// <summary>Level order used by the level select and "next level" (world by world: 1..5, fortress, airship/castle).</summary>
        public static List<string> LevelOrder()
        {
            var ids = new List<string>();
            foreach (var p in Data.List("levels/"))
            {
                if (!p.EndsWith(".lvl", StringComparison.OrdinalIgnoreCase)) continue;
                string id = Path.GetFileNameWithoutExtension(p);
                if (id.StartsWith("_") || id.Length != 3 || id[1] != '-' || !char.IsDigit(id[0])) continue;
                ids.Add(id);
            }
            ids.Sort((a, b) => Rank(a).CompareTo(Rank(b)));
            // the Hammer Bro battle arena (entered from the map) is last: LVL_HB (= the sprites module's SPR_LEVEL_HB)
            foreach (var p in Data.List("levels/"))
                if (string.Equals(Path.GetFileName(p), "hb.lvl", StringComparison.OrdinalIgnoreCase)) { ids.Add("hb"); break; }
            return ids;
        }

        static int Rank(string id)
        {
            int w = id[0] - '0';
            char c = id[2];
            int k = char.IsDigit(c) ? c - '0' : c == 'f' ? 10 : c == 'a' ? 11 : c == 'c' ? 12 : 13;
            return w * 100 + k;
        }

        // ------------------------------------------------------------------------------------------------ export
        public static int Export(string outDir)
        {
            // other modules' include files may not exist yet (their steps run later / may fail): empty stubs
            foreach (var inc0 in new[] { "music.inc", "themes.inc", "spr_ids.inc" })
            {
                string f0 = Path.Combine(outDir, inc0);
                if (!File.Exists(f0)) File.WriteAllText(f0, "; stub (created by the levels step)" + Environment.NewLine);
            }
            var order = LevelOrder();
            var defs = new List<LevelDef>();
            foreach (var id in order)
            {
                var d = LevelLoader.Load(id);
                if (d == null) { Console.WriteLine("  levels: cannot load " + id); return 1; }
                defs.Add(d);
            }
            var packer = new BankPacker();

            // ---------------- tilesets (one per theme used)
            var tilesets = new Dictionary<string, Tileset>();
            foreach (var d in defs)
                foreach (var a in d.Areas)
                {
                    Tileset ts;
                    if (!tilesets.TryGetValue(a.Theme, out ts)) { ts = new Tileset(a.Theme); tilesets[a.Theme] = ts; }
                    ts.AddArea(a);
                }
            var tsOut = new StringBuilder();
            tsOut.AppendLine("; generated by smb4tools snes-export (SnesLevels.cs) - BG1 tilesets");
            tsOut.AppendLine(".p816");
            tsOut.AppendLine(".export eng_ts_dir");
            var tsDir = new List<string>();
            int errors = 0;
            foreach (var th in Themes)
            {
                Tileset ts;
                if (!tilesets.TryGetValue(th, out ts)) { tsDir.Add(null); continue; }
                errors += ts.Build();
                ts.Emit(packer, tsDir.Count);
                tsDir.Add("ts_" + th);
                Console.WriteLine("  tileset " + th + ": " + ts.Summary());
            }
            // ---------------- levels
            var lv = new StringBuilder();
            var dirNames = new List<string>();
            for (int li = 0; li < defs.Count; li++)
            {
                var d = defs[li];
                string lname = "lvl_" + Sym(d.Id);
                var areaNames = new List<string>();
                for (int ai = 0; ai < d.Areas.Count; ai++)
                {
                    var a = d.Areas[ai];
                    string an = lname + "_a" + ai;
                    areaNames.Add(an);
                    EmitArea(packer, an, a, tilesets[a.Theme]);
                }
                var b = new Blob(lname);
                int world = char.IsDigit(d.Id[0]) ? d.Id[0] - '0' : 9;   // hb: row 9 of the test level select
                int kind = d.Kind == "battle" ? 1 : d.Kind == "fortress" ? 2 : d.Kind == "airship" ? 3 : d.Kind == "castle" ? 4 : 0;
                b.Byte(world); b.Byte(kind); b.Word(d.Time);
                b.Byte(d.StartArea); b.Byte(d.StartX); b.Byte(d.StartY); b.Byte(d.Areas.Count);
                b.Byte(d.Links.Count);
                string nm = d.Id.ToUpperInvariant();
                for (int i = 0; i < 4; i++) b.Byte(i < nm.Length ? nm[i] : ' ');
                string title = (d.Title ?? "").ToUpperInvariant();
                for (int i = 0; i < 20; i++) b.Byte(i < title.Length ? title[i] : ' ');
                foreach (var an in areaNames) b.Far(an);
                foreach (var l in d.Links) { b.Byte(l.FromArea); b.Byte(l.FromId); b.Byte(l.ToArea); b.Byte(l.ToId); }
                packer.Add(b);
                dirNames.Add(lname);
            }
            // level directory
            var dir = new Blob("eng_lvl_dir");
            foreach (var n in dirNames) dir.Far(n);
            packer.Add(dir);
            var tsd = new Blob("eng_ts_dir");
            foreach (var n in tsDir) { if (n == null) tsd.Raw("\t.faraddr 0"); else tsd.Far(n); }
            packer.Add(tsd);

            // ---------------- font
            var font = new Blob("eng_font");
            for (int c = 32; c < 96; c++) font.Bytes(FontTile((char)c));
            // extra glyphs 64..: filled arrow, empty arrow, P badge left/right, 'x' small, frame bits
            packer.Add(font);

            // trig tables for the C# Math.Sin motions (exact (int) truncation of the C# doubles)
            var tb = new Blob("eng_tables");
            for (int t = 0; t < 180; t++) tb.Word((int)(Math.Sin(t * 2 * Math.PI / 180.0) * 40 * 16));
            for (int t = 0; t < 240; t++) tb.Word((int)(Math.Sin(t * 2 * Math.PI / 240.0) * 48 * 16));
            for (int t = 0; t < 240; t++) tb.Word(Math.Cos(t * 2 * Math.PI / 240.0) > 0 ? 1 : 0xFFFF);
            for (int t = 0; t < 240; t++) tb.Word((int)(Math.Sin(t * 2 * Math.PI / 240.0) * 56 * 16));   // MovingLift x
            // +1800: generic binary-angle sine for ent_sin (256 steps per turn, value = sin * 32767)
            for (int t = 0; t < 256; t++) tb.Word((int)Math.Round(Math.Sin(t * 2 * Math.PI / 256.0) * 32767));
            packer.Add(tb);

            string asm = packer.Emit(new[] { "eng_lvl_dir", "eng_ts_dir", "eng_font", "eng_tables" });
            if (asm == null) { Console.WriteLine("  levels: ROM banks " + FirstBank + "-" + LastBank + " are full"); return 1; }
            File.WriteAllText(Path.Combine(outDir, "eng_data.s"), "; generated by smb4tools snes-export (SnesLevels.cs)\n.p816\n" +
                "; tolerate missing theme / song symbols from other modules' stubs\n" + SymbolFallbacks(defs) + asm);

            // ---------------- constants
            var inc = new StringBuilder();
            inc.AppendLine("; generated by smb4tools snes-export (SnesLevels.cs)");
            inc.AppendLine("LEVEL_COUNT = " + defs.Count);
            for (int i = 0; i < defs.Count; i++) inc.AppendLine("LVL_" + Sym(defs[i].Id).ToUpperInvariant() + " = " + i);
            for (int i = 0; i < Themes.Length; i++) inc.AppendLine("ETS_" + Themes[i].ToUpperInvariant() + " = " + i);
            foreach (T t in Enum.GetValues(typeof(T))) inc.AppendLine("T_" + t.ToString().ToUpperInvariant() + " = " + (int)t);
            foreach (Content c in Enum.GetValues(typeof(Content))) inc.AppendLine("CT_" + c.ToString().ToUpperInvariant() + " = " + (int)c);
            for (int i = 0; i < Scrolls.Length; i++) inc.AppendLine("SCROLL_" + Scrolls[i].ToUpperInvariant() + " = " + i);
            inc.AppendLine("DYN_EMPTY = 0\nDYN_COIN = 1\nDYN_BRICK = 2\nDYN_USED = 3\nDYN_VINE = 4\nDYN_VINETOP = 5\nDYN_MUNCHER = 6\nDYN_QBLOCK = 7");
            // tile-type property table: bit0 solid, bit1 floor, bit2 slope, bit3 hurts, bit4 bumpable, bit5 lava, bit6 pipe
            inc.Append(".define TILE_PROPS ");
            var props = new List<string>();
            for (int i = 0; i < 64; i++)
            {
                T t = (T)i;
                int p = 0;
                if (i <= (int)T.BigBlockBody)
                {
                    if (TileInfo.Solid(t)) p |= 1;
                    if (TileInfo.Floor(t)) p |= 2;
                    if (TileInfo.Slope(t)) p |= 4;
                    if (TileInfo.Hurts(t)) p |= 8;
                    if (TileInfo.Bumpable(t)) p |= 16;
                    if (TileInfo.Lava(t)) p |= 32;
                    if (TileInfo.Pipe(t)) p |= 64;
                }
                props.Add(p.ToString());
            }
            inc.AppendLine(string.Join(",", props));
            File.WriteAllText(Path.Combine(outDir, "levels.inc"), inc.ToString());
            return errors == 0 ? 0 : 1;
        }

        static string SymbolFallbacks(List<LevelDef> defs)
        {
            var sb = new StringBuilder();
            sb.AppendLine(".include \"themes.inc\"");
            sb.AppendLine(".include \"music.inc\"");
            var names = new SortedSet<string>();
            foreach (var th in Themes) names.Add("THEME_" + th.ToUpperInvariant());
            foreach (var d in defs) foreach (var a in d.Areas) names.Add("SONG_" + a.Music.ToUpperInvariant());
            names.Add("SONG_BOSS"); names.Add("SONG_BOWSER");
            foreach (var n in names) sb.AppendLine(".ifndef " + n + "\n" + n + " = 0\n.endif");
            return sb.ToString();
        }

        public static string Sym(string id) { return id.Replace('-', '_').ToLowerInvariant(); }

        // ------------------------------------------------------------------------------------------------ areas
        static void EmitArea(BankPacker packer, string name, AreaDef a, Tileset ts)
        {
            int w = a.W, h = a.H;
            var tiles = new byte[w * h];
            for (int i = 0; i < tiles.Length; i++) tiles[i] = (byte)a.Tiles[i];
            var gfx = ts.AreaGrid(a);
            var tz = new Blob(name + "_t"); tz.Bytes(Lz.Compress(tiles)); packer.Add(tz);
            var gz = new Blob(name + "_g"); gz.Bytes(Lz.Compress(gfx)); packer.Add(gz);

            var b = new Blob(name);
            b.Byte(w); b.Byte(h);
            b.Byte(Array.IndexOf(Themes, a.Theme));
            b.Raw("\t.byte THEME_" + a.Theme.ToUpperInvariant());
            b.Byte(a.Backdrop >= 0 ? 1 : 0);
            // boss rooms: the boss song is the area song, so its (slow) SPC upload happens under the area-load blank
            // instead of when the boss activates mid-gameplay (C# switches at activation)
            string mus = "SONG_" + a.Music.ToUpperInvariant();
            if (a.Spawns.Exists(s => s.Code == 'Y')) mus = "SONG_BOWSER";
            else if (a.Spawns.Exists(s => s.Code == 'Z' || s.Code == 'K')) mus = "SONG_BOSS";
            b.Raw("\t.byte " + mus);
            int sc = Array.IndexOf(Scrolls, a.Scroll); if (sc < 0) sc = 0;
            b.Byte(sc);
            b.Byte(a.AutoSpeed);
            b.Byte(a.WaterRow < 0 ? 0xFF : a.WaterRow);
            b.Byte(a.GoalX < 0 ? 0xFF : a.GoalX);
            b.Byte(a.GoalY < 0 ? 0 : a.GoalY);
            b.Byte(a.HasSlopes ? 1 : 0);
            b.Byte(a.Theme == "ice" ? 1 : 0);
            b.Word(a.Backdrop >= 0 ? SnesExport.Bgr555(a.Backdrop) : 0);   // bg_flat_color for bg= areas
            b.Far(name + "_t"); b.Far(name + "_g");
            // contents / var (sparse)
            var cont = new List<int>();
            for (int i = 0; i < w * h; i++) if (a.Contents[i] != Content.None) cont.Add(i);
            b.Word(cont.Count);
            foreach (int i in cont) { b.Word(i); b.Byte((int)a.Contents[i]); }
            var vars = new List<int>();
            for (int i = 0; i < w * h; i++) if (a.Var[i] != 0) vars.Add(i);
            b.Word(vars.Count);
            foreach (int i in vars) { b.Word(i); b.Byte(a.Var[i]); }
            // link markers
            var links = new List<int>();
            for (int i = 0; i < w * h; i++) if (a.Link[i] >= 0) links.Add(i);
            b.Byte(links.Count);
            foreach (int i in links) { b.Byte(i % w); b.Byte(i / w); b.Byte(a.Link[i]); }
            // spawns (sorted by x, then y, as the C# loader does)
            b.Word(a.Spawns.Count);
            foreach (var s in a.Spawns) { b.Byte(s.Code); b.Byte(s.X); b.Byte(s.Y); }
            packer.Add(b);
        }

        // ------------------------------------------------------------------------------------------------ font
        static byte[] FontTile(char c)
        {
            // 2bpp: color 1 = light upper rows, 2 = lower rows, 3 = 1-px drop shadow (down-right, down)
            var px = new int[64];
            var g = Font.Glyph(c);
            if (g != null)
            {
                for (int y = 0; y < 8; y++)
                    for (int x = 0; x < 8; x++)
                    {
                        if (g.P[y * 8 + x] == 0) continue;
                        int[,] sh = { { 1, 1 }, { 0, 1 } };
                        for (int k = 0; k < 2; k++)
                        {
                            int sx = x + sh[k, 0], sy = y + sh[k, 1];
                            if (sx < 8 && sy < 8 && px[sy * 8 + sx] == 0) px[sy * 8 + sx] = 3;
                        }
                    }
                for (int y = 0; y < 8; y++)
                    for (int x = 0; x < 8; x++)
                        if (g.P[y * 8 + x] != 0) px[y * 8 + x] = y < 4 ? 1 : 2;
            }
            var o = new byte[16];
            for (int y = 0; y < 8; y++)
            {
                int p0 = 0, p1 = 0;
                for (int x = 0; x < 8; x++)
                {
                    int v = px[y * 8 + x];
                    if ((v & 1) != 0) p0 |= 0x80 >> x;
                    if ((v & 2) != 0) p1 |= 0x80 >> x;
                }
                o[y * 2] = (byte)p0; o[y * 2 + 1] = (byte)p1;
            }
            return o;
        }

