        sealed class AnimSlot { public int Spec; public string Base; public int Count, Shift, ChrBase; public List<int[]> FrameTiles = new List<int[]>(); }

        sealed class Tileset
        {
            public readonly string Theme;
            readonly List<AreaDef> areas = new List<AreaDef>();
            readonly Dictionary<string, Spec> specs = new Dictionary<string, Spec>();
            readonly List<Spec> specList = new List<Spec>();
            readonly Dictionary<AreaDef, byte[]> grids = new Dictionary<AreaDef, byte[]>();
            readonly int[,] dyn = new int[4, 8];
            readonly List<AnimSlot> anims = new List<AnimSlot>();
            readonly List<byte[]> chr = new List<byte[]>();          // 4bpp index arrays (64) per CHR tile
            readonly Dictionary<string, int> chrIndex = new Dictionary<string, int>();
            readonly ushort[][] pals = new ushort[4][];
            readonly List<ushort[]> mtWords = new List<ushort[]>();
            public Tileset(string theme) { Theme = theme; Intern(new Spec()); }

            public void AddArea(AreaDef a) { areas.Add(a); }

            public string Summary() { return mtWords.Count + " metatiles, " + chr.Count + " CHR tiles, " + anims.Count + " animated"; }

            ushort[] ThemePal(string group, out string name)
            {
                string key = Theme + "." + group;
                if (Art.HasPal(key)) { name = key; return Art.Pal(key); }
                if (Art.HasPal("default." + group)) { name = "default." + group; return Art.Pal("default." + group); }
                name = "#fallback"; return Art.P(0x0F, 0x17, 0x27);
            }

            Layer L(string img, string group, bool fh = false, bool fv = false)
            {
                string pn; var p = ThemePal(group, out pn);
                return new Layer { Img = img, Pal = p, PalName = pn, Fh = fh, Fv = fv };
            }

            Layer LP(string img, string palName, bool fh = false)
            {
                return new Layer { Img = img, Pal = Art.Pal(palName), PalName = palName, Fh = fh };
            }

            Layer DecorLayer(string img)
            {
                string k1 = Theme + ".decor." + img, k2 = "decor." + img;
                if (Art.HasPal(k1)) return LP(img, k1);
                if (Art.HasPal(k2)) return LP(img, k2);
                return L(img, "decor");
            }

            int Intern(Spec s)
            {
                string k = s.Key;
                Spec e;
                if (specs.TryGetValue(k, out e)) return e.Id;
                s.Id = specList.Count;
                specs[k] = s; specList.Add(s);
                return s.Id;
            }

            // -------------------------------------------------------------- per-cell images (port of WorldRender)
            static T Get(AreaDef a, int x, int y) { return x < 0 || y < 0 || x >= a.W || y >= a.H ? T.Empty : a.Tiles[y * a.W + x]; }
            static T TileAt(AreaDef a, int tx, int ty)
            {
                if (tx < 0 || tx >= a.W) return ty < 0 ? T.Empty : T.Barrier;
                if (ty < 0 || ty >= a.H) return T.Empty;
                return a.Tiles[ty * a.W + tx];
            }
            static bool IsGround(AreaDef a, int tx, int ty)
            {
                if (tx < 0 || tx >= a.W) { T e = ty >= 0 && ty < a.H ? TileAt(a, Math.Max(0, Math.Min(a.W - 1, tx)), ty) : T.Empty; return e == T.Ground || TileInfo.Slope(e); }
                if (ty >= a.H) return true;
                if (ty < 0) return false;
                T t = a.Tiles[ty * a.W + tx];
                return t == T.Ground || TileInfo.Slope(t);
            }
            string GroundPiece(AreaDef a, int tx, int ty)
            {
                string set;
                if (!GroundSet.TryGetValue(Theme, out set)) set = "grass";
                bool up = IsGround(a, tx, ty - 1);
                T above = TileAt(a, tx, ty - 1);
                if (above == T.SlopeUp && Art.Has("ground." + set + ".sub")) return "ground." + set + ".sub";
                if (above == T.SlopeDown && Art.Has("ground." + set + ".sdb")) return "ground." + set + ".sdb";
                if (set == "rock" || set == "stone" || set == "metal" || set == "wood") return "ground." + set + (up ? ".c" : ".t");
                bool dn = IsGround(a, tx, ty + 1), lf = IsGround(a, tx - 1, ty), rt = IsGround(a, tx + 1, ty);
                string s;
                if (!up)
                {
                    bool wallL = lf && IsGround(a, tx - 1, ty - 1), wallR = rt && IsGround(a, tx + 1, ty - 1);
                    if (wallL && !wallR) s = "itl";
                    else if (wallR && !wallL) s = "itr";
                    else s = !lf && rt ? "tl" : !rt && lf ? "tr" : "t";
                }
                else if (!dn) s = !lf ? "bl" : !rt ? "br" : "b";
                else if (!lf) s = "l";
                else if (!rt) s = "r";
                else s = "c";
                return "ground." + set + "." + s;
            }
            static string BlockPiece(AreaDef a, int tx, int ty, byte color)
            {
                Func<int, int, bool> same = (x, y) => x >= 0 && y >= 0 && x < a.W && y < a.H && (a.Tiles[y * a.W + x] == T.BigBlock || a.Tiles[y * a.W + x] == T.BigBlockBody) && a.Var[y * a.W + x] == color;
                bool up = same(tx, ty - 1), dn = same(tx, ty + 1), lf = same(tx - 1, ty), rt = same(tx + 1, ty);
                string v = !up ? "t" : !dn ? "b" : "";
                string h = !lf ? "l" : !rt ? "r" : "";
                if (v == "" && h == "") return "block.c";
                return "block." + v + h;
            }

            /// <summary>The tile layer as World.DrawTileImage draws it at Frame 0 (animated images use frame 1).</summary>
            Layer TileLayer(AreaDef a, T t, int tx, int ty)
            {
                int W = a.W;
                switch (t)
                {
                    case T.Ground: return L(GroundPiece(a, tx, ty), "ground");
                    case T.Hard: return L("hard", "hard");
                    case T.Brick: return L("brick", "brick");
                    case T.QBlock: return L("qblock.1", "qblock");
                    case T.Used: return L("used", "used");
                    case T.Wood: return L("wood", "wood");
                    case T.Note: return L("note.1", "note");
                    case T.Ice: return L("ice", "ice");
                    case T.Muncher: return L("muncher.1", "muncher");
                    case T.Spike: return L("spike", "spike");
