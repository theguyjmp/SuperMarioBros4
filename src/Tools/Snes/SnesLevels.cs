        /// <summary>One layer of a 16x16 metatile image: an art image drawn with a palette (or a solid black fill).</summary>
        sealed class Layer
        {
            public string Img, PalName; public ushort[] Pal; public bool Fh, Fv, Black;
            public string Key { get { return Black ? "#black" : Img + ":" + PalName + ":" + (Fh ? 1 : 0) + (Fv ? 1 : 0); } }
        }

        sealed class Spec
        {
            public List<Layer> Layers = new List<Layer>();
            public bool Prio;
            public int Id = -1;              // metatile id
            public int AnimSlot = -1;
            public string Key
            {
                get
                {
                    var sb = new StringBuilder();
                    foreach (var l in Layers) sb.Append(l.Key).Append(';');
                    sb.Append(Prio ? "P" : "-");
                    return sb.ToString();
                }
            }
        }

