            Spec CellSpec(AreaDef a, int x, int y, Dictionary<int, List<string>> decor)
            {
                var s = new Spec();
                int i = y * a.W + x;
                T t = a.Tiles[i];
                int goalPx = a.GoalX >= 0 ? (a.GoalX - 2) * 16 : int.MaxValue;
                bool back = a.GoalX >= 0 && x * 16 >= goalPx && y >= a.GoalY - 12 && y < a.GoalY + 4;
                if (back) s.Layers.Add(new Layer { Black = true });
                // water: only the surface row is BG1; the body is BG2's underwater gradient/layers (backgrounds module)
                if (a.WaterRow > 0 && y == a.WaterRow && (t == T.Empty || t == T.Coin))
                    s.Layers.Add(L("water.top1", "water"));
                List<string> dl;
                if (decor.TryGetValue(i, out dl) && x * 16 < goalPx)
                    foreach (var img in dl) s.Layers.Add(DecorLayer(img));
                if (t != T.Empty && t != T.Barrier && t != T.HiddenBlock)
                {
                    Layer tl = t == T.Ground && x * 16 >= goalPx ? L("goal.floor", "goal") : TileLayer(a, t, x, y);
                    if (tl != null) s.Layers.Add(tl);
                    s.Prio = TileInfo.Solid(t);
                }
                s.Layers.RemoveAll(l => !l.Black && !Art.Has(l.Img));
                if (s.Layers.Count == 0) s.Prio = false;
                return s;
            }

