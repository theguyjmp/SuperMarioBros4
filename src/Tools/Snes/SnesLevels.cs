            public int Build()
            {
                int errs = 0;
                // cell specs for every area
                var cellSpec = new Dictionary<AreaDef, int[]>();
                foreach (var a in areas)
                {
                    var decor = new Dictionary<int, List<string>>();
                    foreach (var d in a.Decor)
                    {
                        if (d.X < 0 || d.Y < 0 || d.X >= a.W || d.Y >= a.H) continue;
                        int k = d.Y * a.W + d.X;
                        List<string> l;
                        if (!decor.TryGetValue(k, out l)) { l = new List<string>(); decor[k] = l; }
                        l.Add(d.Img);
                    }
                    var g = new int[a.W * a.H];
                    for (int y = 0; y < a.H; y++)
                        for (int x = 0; x < a.W; x++)
                            g[y * a.W + x] = Intern(CellSpec(a, x, y, decor));
                    cellSpec[a] = g;
                }
                // runtime table for tiles that change: [bg class][DYN_*]
                bool[] used = new bool[4];
                foreach (var a in areas) for (int y = 0; y < a.H; y++) for (int x = 0; x < a.W; x++) used[BgClass(a, x, y)] = true;
                var dummy = new AreaDef { W = 1, H = 1, Tiles = new T[1], Var = new byte[1], Contents = new Content[1] };
                for (int c = 0; c < 4; c++)
                    for (int k = 0; k < 8; k++)
                    {
                        if (!used[c]) { dyn[c, k] = dyn[0, k]; continue; }
                        var s = new Spec();
                        if (k <= 1) s.Layers.AddRange(BgLayers(c));
                        else if (c == 3) s.Layers.Add(new Layer { Black = true });
                        switch (k)
                        {
                            case 1: s.Layers.Add(LP("coin.1", "coin")); break;
                            case 2: s.Layers.Add(L("brick", "brick")); s.Prio = true; break;
                            case 3: s.Layers.Add(L("used", "used")); s.Prio = true; break;
                            case 4: s.Layers.Add(L("vine", "vine")); break;
                            case 5: s.Layers.Add(L("vine.top", "vine")); break;
                            case 6: s.Layers.Add(L("muncher.1", "muncher")); s.Prio = true; break;
                            case 7: s.Layers.Add(L("qblock.1", "qblock")); s.Prio = true; break;
                        }
                        s.Layers.RemoveAll(l => !l.Black && !Art.Has(l.Img));
                        dyn[c, k] = Intern(s);
                    }
                if (specList.Count > 256) { Console.WriteLine("  tileset " + Theme + ": " + specList.Count + " metatiles (max 256)"); errs++; }
                foreach (var a in areas)
                {
                    var g = cellSpec[a];
                    var b = new byte[g.Length];
                    for (int i = 0; i < g.Length; i++) b[i] = (byte)g[i];
                    grids[a] = b;
                }

                // ---- render every spec (all animation frames) into 16x16 BGR555 pixels (-1 = transparent)
                var frames = new List<List<int[]>>();   // per spec: list of frames
                for (int si = 0; si < specList.Count; si++)
                {
                    var s = specList[si];
                    string animBase = null;
                    foreach (var l in s.Layers) if (!l.Black && Anims.ContainsKey(l.Img)) { animBase = l.Img; break; }
                    var fl = new List<int[]>();
                    if (animBase == null) fl.Add(Render(s.Layers, null, null));
                    else
                    {
                        var an = Anims[animBase];
                        foreach (var fname in an.Key) fl.Add(Render(s.Layers, animBase, Art.Has(fname) ? fname : animBase));
                        var slot = new AnimSlot { Spec = si, Base = animBase, Count = an.Key.Length, Shift = an.Value };
                        s.AnimSlot = anims.Count; anims.Add(slot);
                    }
                    frames.Add(fl);
                }

                // ---- palette items: one per 8x8 tile position (animated: union over frames)
                var items = new List<Item>();
                var itemOf = new Dictionary<long, Item>();
                for (int si = 0; si < specList.Count; si++)
                    for (int q = 0; q < 4; q++)
                    {
                        var it = new Item();
                        foreach (var f in frames[si])
                            for (int y = 0; y < 8; y++)
                                for (int x = 0; x < 8; x++)
                                {
                                    int c = f[(y + (q >> 1) * 8) * 16 + x + (q & 1) * 8];
                                    if (c < 0) continue;
                                    int n; it.Hist.TryGetValue(c, out n); it.Hist[c] = n + 1;
                                }
                        items.Add(it);
                        itemOf[(long)si * 4 + q] = it;
                    }
                Quantize(items);
                for (int p = 0; p < 4; p++) pals[p] = new ushort[16];
                for (int p = 0; p < 4; p++) { int k = 1; foreach (var c in palSets[p]) pals[p][k++] = (ushort)c; }

                // ---- CHR: tile 0 blank, animated slots first (fixed tiles), then deduplicated static tiles
                chr.Add(new byte[64]);
                chrIndex[Convert.ToBase64String(new byte[64])] = 0;
                foreach (var slot in anims)
                {
                    slot.ChrBase = chr.Count;
                    for (int q = 0; q < 4; q++) chr.Add(null);
                }
                for (int si = 0; si < specList.Count; si++)
                {
                    var s = specList[si];
                    var words = new ushort[4];
                    for (int q = 0; q < 4; q++)
                    {
                        var it = itemOf[(long)si * 4 + q];
                        int pal = it.Pal;
                        if (s.AnimSlot >= 0)
                        {
                            var slot = anims[s.AnimSlot];
                            int tile = slot.ChrBase + q;
                            for (int f = 0; f < frames[si].Count; f++)
                            {
                                var idx = TileIndices(frames[si][f], q, pal);
                                if (f == 0) chr[tile] = idx;
                                if (slot.FrameTiles.Count <= f) slot.FrameTiles.Add(new int[4]);
                                slot.FrameTiles[f][q] = chr.Count; // placeholder: store frame tile data separately
                                frameData.Add(idx);
                                slot.FrameTiles[f][q] = frameData.Count - 1;
                            }
                            words[q] = (ushort)(tile | ((2 + pal) << 10) | (s.Prio ? 0x2000 : 0));
                        }
                        else
                        {
                            var idx = TileIndices(frames[si][0], q, pal);
                            bool blank = true; foreach (var v in idx) if (v != 0) { blank = false; break; }
                            if (blank) { words[q] = (ushort)((2 + pal) << 10 | (s.Prio ? 0x2000 : 0)); continue; }
                            int tile; bool fh, fv;
                            FindOrAdd(idx, out tile, out fh, out fv);
                            words[q] = (ushort)(tile | ((2 + pal) << 10) | (s.Prio ? 0x2000 : 0) | (fh ? 0x4000 : 0) | (fv ? 0x8000 : 0));
                        }
                    }
                    mtWords.Add(words);
                }
                if (chr.Count > 768) { Console.WriteLine("  tileset " + Theme + ": " + chr.Count + " CHR tiles (max 768)"); errs++; }
                return errs;
            }

            readonly List<byte[]> frameData = new List<byte[]>();

            void FindOrAdd(byte[] idx, out int tile, out bool fh, out bool fv)
            {
                for (int v = 0; v < 4; v++)
                {
                    bool h = (v & 1) != 0, vv = (v & 2) != 0;
                    var t = new byte[64];
                    for (int y = 0; y < 8; y++) for (int x = 0; x < 8; x++) t[y * 8 + x] = idx[(vv ? 7 - y : y) * 8 + (h ? 7 - x : x)];
                    int k;
                    if (chrIndex.TryGetValue(Convert.ToBase64String(t), out k)) { tile = k; fh = h; fv = vv; return; }
                }
                tile = chr.Count; fh = false; fv = false;
                chr.Add(idx);
                chrIndex[Convert.ToBase64String(idx)] = tile;
            }

            byte[] TileIndices(int[] px16, int q, int pal)
            {
                var o = new byte[64];
                for (int y = 0; y < 8; y++)
                    for (int x = 0; x < 8; x++)
                    {
                        int c = px16[(y + (q >> 1) * 8) * 16 + x + (q & 1) * 8];
                        o[y * 8 + x] = c < 0 ? (byte)0 : (byte)Nearest(pal, c);
                    }
                return o;
            }

            int Nearest(int pal, int c)
            {
                int best = 1, bd = int.MaxValue;
                for (int k = 1; k < 16; k++)
                {
                    if (k > palSets[pal].Count) break;
                    int d = Dist(pals[pal][k], c);
                    if (d < bd) { bd = d; best = k; }
                }
                return best;
            }

            static int[] Render(List<Layer> layers, string animBase, string animFrame)
            {
                var o = new int[256];
                for (int i = 0; i < 256; i++) o[i] = -1;
                foreach (var l in layers)
                {
                    if (l.Black) { for (int i = 0; i < 256; i++) o[i] = 0; continue; }
                    string name = animBase != null && l.Img == animBase ? animFrame : l.Img;
                    var img = Art.Get(name);
                    int last = l.Pal.Length - 1;
                    for (int y = 0; y < 16 && y < img.H; y++)
                        for (int x = 0; x < 16 && x < img.W; x++)
                        {
                            int sx = l.Fh ? img.W - 1 - x : x, sy = l.Fv ? img.H - 1 - y : y;
                            if (sx < 0 || sy < 0 || sx >= img.W || sy >= img.H) continue;
                            int v = img.P[sy * img.W + sx];
                            if (v == 0) continue;
                            int ci = l.Pal[v <= last ? v : last];
                            int rgb = NesPalette.RgbOf(ci);
                            o[y * 16 + x] = ((rgb >> 19) & 31) | (((rgb >> 11) & 31) << 5) | (((rgb >> 3) & 31) << 10);
                        }
                }
                return o;
            }

            // -------------------------------------------------------------- palette clustering: 4 palettes x 15 colors
            sealed class Item { public Dictionary<int, int> Hist = new Dictionary<int, int>(); public int Pal; }
            readonly List<int>[] palSets = new List<int>[4];

            static int Dist(int a, int b)
            {
                int dr = (a & 31) - (b & 31), dg = ((a >> 5) & 31) - ((b >> 5) & 31), db = ((a >> 10) & 31) - ((b >> 10) & 31);
                return 2 * dr * dr + 4 * dg * dg + 3 * db * db;
            }

            void Quantize(List<Item> items)
            {
                var sets = new HashSet<int>[4];
                for (int p = 0; p < 4; p++) sets[p] = new HashSet<int>();
                var order = new List<Item>(items);
                order.Sort((a, b) => b.Hist.Count.CompareTo(a.Hist.Count));
                foreach (var it in order)
                {
                    if (it.Hist.Count == 0) { it.Pal = 0; continue; }
                    int best = -1, bestNew = int.MaxValue, bestSize = int.MaxValue;
                    for (int p = 0; p < 4; p++)
                    {
                        int nw = 0; foreach (var c in it.Hist.Keys) if (!sets[p].Contains(c)) nw++;
                        if (sets[p].Count + nw > 15) continue;
                        if (nw < bestNew || nw == bestNew && sets[p].Count > bestSize) { best = p; bestNew = nw; bestSize = sets[p].Count; }
                    }
                    if (best < 0)
                    {
                        long bc = long.MaxValue;
                        for (int p = 0; p < 4; p++)
                        {
                            long cost = 0;
                            foreach (var kv in it.Hist)
                            {
                                if (sets[p].Contains(kv.Key)) continue;
                                int md = int.MaxValue; foreach (var c in sets[p]) md = Math.Min(md, Dist(c, kv.Key));
                                cost += (long)kv.Value * (md == int.MaxValue ? 0 : md);
                            }
                            if (cost < bc) { bc = cost; best = p; }
                        }
                    }
                    it.Pal = best;
                    foreach (var c in it.Hist.Keys) sets[best].Add(c);
                }
                // reduce overflowing palettes by merging the closest pair (keep the more used color)
                for (int p = 0; p < 4; p++)
                {
                    var wgt = new Dictionary<int, long>();
                    foreach (var it in items) if (it.Pal == p) foreach (var kv in it.Hist) { long n; wgt.TryGetValue(kv.Key, out n); wgt[kv.Key] = n + kv.Value; }
                    var cols = new List<int>(wgt.Keys);
                    while (cols.Count > 15)
                    {
                        int ba = 0, bb = 1; long bd = long.MaxValue;
                        for (int i = 0; i < cols.Count; i++)
                            for (int j = i + 1; j < cols.Count; j++)
                            {
                                long d = (long)Dist(cols[i], cols[j]) * Math.Min(wgt[cols[i]], wgt[cols[j]]);
                                if (d < bd) { bd = d; ba = i; bb = j; }
                            }
                        int keep = wgt[cols[ba]] >= wgt[cols[bb]] ? ba : bb, drop = keep == ba ? bb : ba;
                        wgt[cols[keep]] += wgt[cols[drop]];
                        cols.RemoveAt(drop);
                    }
                    cols.Sort((a, b) => Lum(a).CompareTo(Lum(b)));
                    palSets[p] = cols;
                }
                // tiles whose palette ended up empty-ish still map to nearest; refine: each item to its best palette
                for (int p = 0; p < 4; p++) { pals[p] = new ushort[16]; int k = 1; foreach (var c in palSets[p]) pals[p][k++] = (ushort)c; }
                foreach (var it in items)
                {
                    if (it.Hist.Count == 0) continue;
                    long bestE = long.MaxValue; int bp = it.Pal;
                    for (int p = 0; p < 4; p++)
                    {
                        if (palSets[p].Count == 0) continue;
                        long e = 0;
                        foreach (var kv in it.Hist) { int md = int.MaxValue; foreach (var c in palSets[p]) md = Math.Min(md, Dist(c, kv.Key)); e += (long)md * kv.Value; }
                        if (e < bestE || e == bestE && p == it.Pal) { bestE = e; bp = p; }
                    }
                    it.Pal = bp;
                }
            }

            static int Lum(int c) { return (c & 31) * 3 + ((c >> 5) & 31) * 6 + ((c >> 10) & 31); }

            // -------------------------------------------------------------- output
            public void Emit(BankPacker packer, int themeIndex)
            {
                string n = "ts_" + Theme;
                // CHR (may be up to 24 KB: its own blob, split in two if > 16 KB so blobs pack well)
                var chrBytes = new List<byte>();
                foreach (var t in chr) chrBytes.AddRange(Planar(t ?? new byte[64]));
                var cb = new Blob(n + "_chr"); cb.Bytes(chrBytes.ToArray()); packer.Add(cb);
                var mt = new Blob(n + "_mt");
                foreach (var w in mtWords) foreach (var x in w) mt.Word(x);
                packer.Add(mt);
                var an = new Blob(n + "_anim");
                foreach (var s in anims)
                    for (int f = 0; f < s.Count; f++)
                        for (int q = 0; q < 4; q++) an.Bytes(Planar(frameData[s.FrameTiles[f][q]]));
                if (anims.Count > 0) packer.Add(an);
                var h = new Blob(n);
                h.Far(n + "_chr"); h.Word(chrBytes.Count);
                h.Far(n + "_mt"); h.Word(mtWords.Count);
                for (int p = 0; p < 4; p++) for (int k = 0; k < 16; k++) h.Word(pals[p][k]);
                for (int c = 0; c < 4; c++) for (int k = 0; k < 8; k++) h.Byte(dyn[c, k]);
                h.Byte(anims.Count);
                int off = 0;
                foreach (var s in anims)
                {
                    h.Word(s.ChrBase * 16);        // VRAM word address of the slot's 4 tiles
                    h.Byte(s.Count); h.Byte(s.Shift);
                    if (anims.Count > 0) h.Raw("\t.faraddr " + n + "_anim+" + off);
                    off += s.Count * 128;
                }
                packer.Add(h);
            }

            static byte[] Planar(byte[] idx)
            {
                var o = new byte[32];
                for (int y = 0; y < 8; y++)
                {
                    int b0 = 0, b1 = 0, b2 = 0, b3 = 0;
                    for (int x = 0; x < 8; x++)
                    {
                        int v = idx[y * 8 + x], m = 0x80 >> x;
                        if ((v & 1) != 0) b0 |= m; if ((v & 2) != 0) b1 |= m; if ((v & 4) != 0) b2 |= m; if ((v & 8) != 0) b3 |= m;
                    }
                    o[y * 2] = (byte)b0; o[y * 2 + 1] = (byte)b1; o[16 + y * 2] = (byte)b2; o[16 + y * 2 + 1] = (byte)b3;
                }
                return o;
            }
        }

        // ================================================================================================ output helpers
        /// <summary>A labelled chunk of ROM data that must not cross a 32 KB LoROM bank.</summary>
        public sealed class Blob
        {
            public readonly string Name;
            public int Size;
            readonly StringBuilder sb = new StringBuilder();
            readonly List<byte> pending = new List<byte>();
            public Blob(string name) { Name = name; }
            void Flush()
            {
                for (int i = 0; i < pending.Count; i += 32)
                {
                    sb.Append("\t.byte ");
                    for (int k = i; k < Math.Min(pending.Count, i + 32); k++) { if (k > i) sb.Append(','); sb.Append(pending[k]); }
                    sb.Append('\n');
                }
                pending.Clear();
            }
            public void Byte(int v) { pending.Add((byte)v); Size++; }
            public void Bytes(byte[] v) { pending.AddRange(v); Size += v.Length; }
            public void Word(int v) { Byte(v & 255); Byte((v >> 8) & 255); }
            public void Far(string label) { Flush(); sb.Append("\t.faraddr " + label + "\n"); Size += 3; }
            /// <summary>Raw line; must be exactly one byte unless it is a .faraddr (3 bytes).</summary>
            public void Raw(string line) { Flush(); sb.Append(line + "\n"); Size += line.Contains(".faraddr") ? 3 : 1; }
            public string Text { get { Flush(); return sb.ToString(); } }
        }

        public sealed class BankPacker
        {
            readonly List<Blob> blobs = new List<Blob>();
            public void Add(Blob b) { blobs.Add(b); }
            public string Emit(string[] exports)
            {
                // first-fit decreasing into BANK40..BANK55
                var sorted = new List<Blob>(blobs);
                sorted.Sort((a, b) => b.Size.CompareTo(a.Size));
                int nb = LastBank - FirstBank + 1;
                var fill = new int[nb];
                var content = new List<Blob>[nb];
                for (int i = 0; i < nb; i++) content[i] = new List<Blob>();
                foreach (var b in sorted)
                {
                    int k = -1;
                    for (int i = 0; i < nb; i++) if (fill[i] + b.Size <= 0x8000) { k = i; break; }
                    if (k < 0) return null;
                    fill[k] += b.Size; content[k].Add(b);
                }
                var sb = new StringBuilder();
                foreach (var e in exports) sb.Append(".export " + e + "\n");
                int total = 0;
                for (int i = 0; i < nb; i++)
                {
                    if (content[i].Count == 0) continue;
                    sb.Append("\n.segment \"BANK" + (FirstBank + i) + "\"\n");
                    foreach (var b in content[i]) { sb.Append(b.Name + ":\n"); sb.Append(b.Text); }
                    total += fill[i];
                }
                Console.WriteLine("  levels+tiles: " + total / 1024 + " KB in banks " + FirstBank + "-" + LastBank);
                return sb.ToString();
            }
        }

        /// <summary>
        /// Byte-oriented LZ77: control byte c &lt; $80 = (c+1) literal bytes follow; c &gt;= $80 = copy (c&amp;$7F)+3 bytes
        /// from 'distance' bytes back (16-bit little-endian distance follows). The decoder knows the output size.
        /// </summary>
        public static class Lz
        {
            public static byte[] Compress(byte[] src)
            {
                var o = new List<byte>();
                var lit = new List<byte>();
                var head = new Dictionary<int, List<int>>();
                int i = 0;
                Action flush = () =>
                {
                    for (int k = 0; k < lit.Count; k += 128)
                    {
                        int n = Math.Min(128, lit.Count - k);
                        o.Add((byte)(n - 1));
                        for (int j = 0; j < n; j++) o.Add(lit[k + j]);
                    }
                    lit.Clear();
                };
                while (i < src.Length)
                {
                    int bestLen = 0, bestDist = 0;
                    if (i + 3 <= src.Length)
                    {
                        int key = src[i] | src[i + 1] << 8 | src[i + 2] << 16;
                        List<int> cand;
                        if (head.TryGetValue(key, out cand))
                        {
                            for (int c = cand.Count - 1; c >= 0 && c >= cand.Count - 256; c--)
                            {
                                int p = cand[c];
                                int len = 0;
                                while (i + len < src.Length && len < 130 && src[p + len] == src[i + len]) len++;
                                if (len > bestLen) { bestLen = len; bestDist = i - p; if (len == 130) break; }
                            }
                        }
                    }
                    int step = bestLen >= 3 ? bestLen : 1;
                    if (bestLen >= 3)
                    {
                        flush();
                        o.Add((byte)(0x80 | (bestLen - 3)));
                        o.Add((byte)(bestDist & 255)); o.Add((byte)(bestDist >> 8));
                    }
                    else lit.Add(src[i]);
                    for (int k = 0; k < step; k++)
                    {
                        int j = i + k;
                        if (j + 3 <= src.Length)
                        {
                            int key = src[j] | src[j + 1] << 8 | src[j + 2] << 16;
                            List<int> l;
                            if (!head.TryGetValue(key, out l)) { l = new List<int>(); head[key] = l; }
                            l.Add(j);
                        }
                    }
                    i += step;
                }
                flush();
                // self-check
                var d = Decompress(o.ToArray(), src.Length);
                for (int k = 0; k < src.Length; k++) if (d[k] != src[k]) throw new Exception("LZ self-check failed");
                return o.ToArray();
            }

            public static byte[] Decompress(byte[] z, int n)
            {
                var o = new byte[n];
                int i = 0, j = 0;
                while (j < n)
                {
                    int c = z[i++];
                    if (c < 0x80) { for (int k = 0; k <= c; k++) o[j++] = z[i++]; }
                    else { int len = (c & 0x7F) + 3, dist = z[i] | z[i + 1] << 8; i += 2; for (int k = 0; k < len; k++, j++) o[j] = o[j - dist]; }
                }
                return o;
            }
        }
    }
